"""RFM (Recency, Frequency, Monetary) Analysis Module for CustomerLens.

Transforms transaction-level customer purchase records into customer-level
behavioral features, calculates transparent quantile-based RFM scores,
assigns rule-based analytical customer segments, and provides validation utilities.
"""

